using System.Text;
using System.Text.RegularExpressions;
using YamAuth.CodeGen.Schema;

namespace YamAuth.CodeGen.Generators;

/// <summary>
/// 为 CodeGen CRUD 的 Create/Update DTO 生成 FluentValidation 桩。
/// 输出至 YamAuth.Api/Validators/Generated/*.g.cs；手写校验器（如 User）在生成时跳过。
/// </summary>
public class ValidatorGenerator
{
    public string ApiProjectPath { get; init; } = "";
    public string DtosProjectPath { get; init; } = "";

    static readonly HashSet<string> ManualValidatorEntities = new(StringComparer.OrdinalIgnoreCase)
    {
        "User"
    };

    public void Generate(IReadOnlyList<TableInfo> tables)
    {
        var outDir = Path.Combine(ApiProjectPath, "Validators", "Generated");
        if (Directory.Exists(outDir))
        {
            foreach (var old in Directory.GetFiles(outDir, "*.g.cs"))
                File.Delete(old);
        }
        Directory.CreateDirectory(outDir);

        var eligible = tables
            .Where(ShouldInclude)
            .OrderBy(t => t.Module)
            .ThenBy(t => t.EntityName)
            .ToList();

        foreach (var grp in eligible.GroupBy(t => t.Module))
        {
            var path = Path.Combine(outDir, $"{grp.Key}Validators.g.cs");
            File.WriteAllText(path, BuildModuleFile(grp.Key, grp.ToList(), DtosProjectPath));
        }
    }

    bool ShouldInclude(TableInfo t)
    {
        if (ManualValidatorEntities.Contains(t.EntityName)) return false;
        if (t.EntityName.Contains("i18n", StringComparison.OrdinalIgnoreCase)) return false;
        if (t.EntityName.Equals("RefreshToken", StringComparison.OrdinalIgnoreCase)) return false;
        if (t.EntityName.Equals("PasswordResetToken", StringComparison.OrdinalIgnoreCase)) return false;

        var createDto = Path.Combine(DtosProjectPath, t.Module, $"{t.EntityName}CreateDto.cs");
        var updateDto = Path.Combine(DtosProjectPath, t.Module, $"{t.EntityName}UpdateDto.cs");
        return File.Exists(createDto) && File.Exists(updateDto);
    }

    static void AppendCreateValidator(StringBuilder sb, TableInfo t, IReadOnlySet<string> dtoProps)
    {
        sb.AppendLine($"public sealed class {t.EntityName}CreateDtoValidator : AbstractValidator<{t.EntityName}CreateDto>");
        sb.AppendLine("{");
        sb.AppendLine($"    public {t.EntityName}CreateDtoValidator()");
        sb.AppendLine("    {");
        foreach (var c in t.Columns.Where(DtoColumnRules.IncludeInWriteDto).Where(c => dtoProps.Contains(c.Name)))
            AppendCreateRules(sb, c);
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    static void AppendUpdateValidator(StringBuilder sb, TableInfo t, IReadOnlySet<string> dtoProps)
    {
        sb.AppendLine($"public sealed class {t.EntityName}UpdateDtoValidator : AbstractValidator<{t.EntityName}UpdateDto>");
        sb.AppendLine("{");
        sb.AppendLine($"    public {t.EntityName}UpdateDtoValidator()");
        sb.AppendLine("    {");
        foreach (var c in t.Columns.Where(DtoColumnRules.IncludeInWriteDto).Where(c => dtoProps.Contains(c.Name)))
            AppendUpdateRules(sb, c);
        sb.AppendLine("    }");
        sb.AppendLine("}");
    }

    static string BuildModuleFile(string module, IReadOnlyList<TableInfo> tables, string dtosProjectPath)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// CodeGen 生成：Create/Update DTO 校验桩。可按业务补充规则；重新运行 CodeGen 会覆盖本文件。");
        sb.AppendLine("using FluentValidation;");
        sb.AppendLine($"using YamAuth.Dtos.{module};");
        sb.AppendLine();
        sb.AppendLine("namespace YamAuth.Api.Validators.Generated;");
        sb.AppendLine();

        foreach (var t in tables)
        {
            var createProps = ReadDtoPropertyNames(Path.Combine(dtosProjectPath, module, $"{t.EntityName}CreateDto.cs"));
            var updateProps = ReadDtoPropertyNames(Path.Combine(dtosProjectPath, module, $"{t.EntityName}UpdateDto.cs"));
            AppendCreateValidator(sb, t, createProps);
            sb.AppendLine();
            AppendUpdateValidator(sb, t, updateProps);
            sb.AppendLine();
        }

        return sb.ToString();
    }

    static HashSet<string> ReadDtoPropertyNames(string dtoPath)
    {
        var set = new HashSet<string>(StringComparer.Ordinal);
        if (!File.Exists(dtoPath)) return set;
        var pattern = new Regex(@"^\s*public\s+[\w<>,\?\[\]]+\s+(\w+)\s+\{", RegexOptions.Compiled);
        foreach (var line in File.ReadAllLines(dtoPath))
        {
            var m = pattern.Match(line);
            if (m.Success) set.Add(m.Groups[1].Value);
        }
        return set;
    }

    static void AppendCreateRules(StringBuilder sb, ColumnInfo c)
    {
        if (c.Name == "Password")
        {
            sb.AppendLine("        RuleFor(x => x.Password)");
            sb.AppendLine("            .NotEmpty().WithMessage(\"请输入密码\")");
            sb.AppendLine("            .MinimumLength(6).WithMessage(\"密码至少 6 位\")");
            sb.AppendLine("            .MaximumLength(128);");
            return;
        }

        var type = TypeMapper.ToCSharp(c);
        if (type is not ("string" or "string?")) return;

        var prop = $"x => x.{c.Name}";
        var maxLen = DtoColumnRules.CharMaxLength(c);

        if (c.Name.Equals("Email", StringComparison.OrdinalIgnoreCase))
        {
            sb.AppendLine($"        RuleFor({prop})");
            sb.AppendLine("            .NotEmpty().WithMessage(\"请输入邮箱\")");
            sb.AppendLine("            .EmailAddress().WithMessage(\"邮箱格式不正确\")");
            if (maxLen > 0)
                sb.AppendLine($"            .MaximumLength({maxLen});");
            else
                sb.AppendLine("            .MaximumLength(128);");
            return;
        }

        if (DtoColumnRules.IsNonNullableString(c, type))
        {
            sb.Append($"        RuleFor({prop}).NotEmpty()");
            if (maxLen > 0)
                sb.AppendLine($".MaximumLength({maxLen});");
            else
                sb.AppendLine(";");
            return;
        }

        if (maxLen > 0)
            sb.AppendLine($"        RuleFor({prop}).MaximumLength({maxLen});");
    }

    static void AppendUpdateRules(StringBuilder sb, ColumnInfo c)
    {
        if (c.Name == "Password")
        {
            sb.AppendLine("        RuleFor(x => x.Password)");
            sb.AppendLine("            .MinimumLength(6).WithMessage(\"密码至少 6 位\")");
            sb.AppendLine("            .MaximumLength(128)");
            sb.AppendLine("            .When(x => !string.IsNullOrWhiteSpace(x.Password));");
            return;
        }

        var type = TypeMapper.ToCSharp(c);
        if (type is not ("string" or "string?")) return;

        var prop = $"x => x.{c.Name}";
        var maxLen = DtoColumnRules.CharMaxLength(c);

        if (c.Name.Equals("Email", StringComparison.OrdinalIgnoreCase))
        {
            sb.AppendLine($"        RuleFor({prop})");
            sb.AppendLine("            .NotEmpty().WithMessage(\"请输入邮箱\")");
            sb.AppendLine("            .EmailAddress().WithMessage(\"邮箱格式不正确\")");
            if (maxLen > 0)
                sb.AppendLine($"            .MaximumLength({maxLen});");
            else
                sb.AppendLine("            .MaximumLength(128);");
            return;
        }

        if (DtoColumnRules.IsNonNullableString(c, type))
        {
            sb.Append($"        RuleFor({prop}).NotEmpty()");
            if (maxLen > 0)
                sb.AppendLine($".MaximumLength({maxLen});");
            else
                sb.AppendLine(";");
            return;
        }

        if (maxLen > 0)
            sb.AppendLine($"        RuleFor({prop}).MaximumLength({maxLen});");
    }
}
